//! M7-T2 acceptance: a producer source that calls a phase-2-generated sender
//! stub type-checks through the phase-1 metadata `cargo check`.
//!
//! Phase 1 runs the cross-binary pass in **metadata mode**, where the real
//! `pub struct <Task>;` sender stubs — derived in phase 2 from `system.json` —
//! do not exist yet. The pass emits a permissive shim for every
//! `Task::cross_spawn` target the source mentions, so the metadata check
//! accepts the call. This test expands a producer through the metadata pass and
//! the core pass and compiles the expansion on the host; without the shim the
//! `PingTask::cross_spawn` call would not resolve.

use std::path::{Path, PathBuf};
use std::process::Command;

use quote::quote;
use rticx_core::RticMacroBuilder;
use rticx_core::mock_backend::MockCoreBackend;
use rticx_xbin_pass::XbinPass;

/// A producer that calls the `PingTask` sender stub it does not declare (the
/// M4 application declares the receiver). The pass generates the real stub in
/// phase 2; the metadata shim lets phase 1 type-check the call.
fn producer_app() -> syn::ItemMod {
    syn::parse_quote! {
        mod app {
            #[idle]
            struct Idle;

            impl RticIdleTask for Idle {
                fn exec(&mut self) -> ! {
                    let _ = PingTask::cross_spawn(ipc_types::PingMsg { seq: 1, value: 2 });
                    loop {
                        core::hint::spin_loop();
                    }
                }
            }

            #[init]
            fn init() -> TaskInits {
                TaskInits { idle: Idle }
            }
        }
    }
}

fn producer_args() -> proc_macro2::TokenStream {
    quote!(
        device = pac,
        cores = 1,
        core_ids = [0],
        external_cores = [1]
    )
}

fn cargo() -> PathBuf {
    std::env::var_os("CARGO")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("cargo"))
}

/// Writes the throwaway crate that compiles the metadata expansion (a stub PAC
/// and `ipc-types`; the shim is generic, so `PingMsg` needs no trait
/// implementation).
fn write_project(root: &Path, expanded: &str) {
    let rt = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../rticx-xbin-rt")
        .canonicalize()
        .expect("the runtime crate ships with the workspace");

    std::fs::create_dir_all(root.join("src")).expect("src dir");
    std::fs::write(
        root.join("Cargo.toml"),
        "[package]\nname = \"xbin-metadata-shim\"\nversion = \"0.0.0\"\nedition = \"2024\"\n\
         publish = false\n\n\
         [dependencies]\n\
         pac = { path = \"pac\" }\n\
         ipc-types = { path = \"ipc-types\" }\n\n\
         [workspace]\n",
    )
    .expect("project manifest");
    std::fs::write(
        root.join("src/lib.rs"),
        format!(
            "// @generated by the M7-T2 metadata shim test\n\
             #![allow(static_mut_refs, unused_imports, unused_variables, dead_code, \
             non_camel_case_types, non_snake_case)]\n\n{expanded}\n"
        ),
    )
    .expect("expansion");

    std::fs::create_dir_all(root.join("pac/src")).expect("pac dir");
    std::fs::write(
        root.join("pac/Cargo.toml"),
        "[package]\nname = \"pac\"\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n",
    )
    .expect("pac manifest");
    std::fs::write(root.join("pac/src/lib.rs"), "").expect("pac source");

    std::fs::create_dir_all(root.join("ipc-types/src")).expect("ipc-types dir");
    std::fs::write(
        root.join("ipc-types/Cargo.toml"),
        format!(
            "[package]\nname = \"ipc-types\"\nversion = \"0.0.0\"\nedition = \"2024\"\n\
             publish = false\n\n\
             [dependencies]\nrticx-xbin-rt = {{ path = \"{}\" }}\n",
            rt.display()
        ),
    )
    .expect("ipc-types manifest");
    std::fs::write(
        root.join("ipc-types/src/lib.rs"),
        "//! Stand-in for the `cargo xbin sync`-generated crate.\n\
         #![no_std]\n\n\
         #[repr(C)]\n\
         #[derive(Clone, Copy)]\n\
         pub struct PingMsg {\n\
             pub seq: u32,\n\
             pub value: u32,\n\
         }\n",
    )
    .expect("ipc-types source");
}

#[test]
fn metadata_check_accepts_a_generated_sender_stub() {
    let dir = tempfile::tempdir().expect("tempdir");
    let pass = XbinPass::with_manifest(dir.path(), "app-m7", "m7");
    assert!(pass.is_metadata_mode());

    let mut builder = RticMacroBuilder::new(MockCoreBackend);
    builder.bind_pre_core_pass(pass);
    let expanded = builder
        .build_rtic_macro2(producer_args(), producer_app(), None)
        .to_string();

    assert!(
        !expanded.contains("compile_error"),
        "the metadata pipeline failed: {expanded}"
    );
    assert!(
        expanded.contains("pub struct PingTask"),
        "the metadata sender shim is missing: {expanded}"
    );
    assert!(
        expanded.contains("fn cross_spawn"),
        "the shim's `cross_spawn` is missing: {expanded}"
    );

    let project = dir.path().join("project");
    write_project(&project, &expanded);

    let output = Command::new(cargo())
        .arg("build")
        .arg("--quiet")
        .arg("--offline")
        .arg("--manifest-path")
        .arg(project.join("Cargo.toml"))
        .env("CARGO_TARGET_DIR", project.join("target"))
        .output()
        .expect("failed to run cargo");
    assert!(
        output.status.success(),
        "the metadata expansion with a `cross_spawn` call failed to compile:\n{}",
        String::from_utf8_lossy(&output.stderr)
    );
}
