/// The generated `ipc_types.rs` stand-in: the fixture's `EncryptReq` type, as
/// `cargo xbin sync` emits it next to `system.json` (M1-T7). The pass re-emits
/// it into the `#[app]` module, replacing the retired checked-in crate.
const IPC_TYPES_RS: &str = "\
// @generated by `cargo xbin sync`\n\
#[repr(C)]\n\
#[derive(Clone, Copy)]\n\
pub struct EncryptReq {\n\
    pub addr: u32,\n\
    pub len: u32,\n\
    pub key: u32,\n\
}\n\
const _: () = {\n\
    assert!(core::mem::size_of::<EncryptReq>() == 12);\n\
    assert!(core::mem::align_of::<EncryptReq>() == 4);\n\
};\n\
unsafe impl CrossCoreMessage for EncryptReq {}\n";

/// Code-generation backend of the compile fixture.
struct CompileBackend;

impl XbinPassBackend for CompileBackend {
    fn rt_path(&self) -> syn::Path {
        syn::parse_quote!(rticx_xbin_rt)
    }

    fn current_global_core_id(&self) -> syn::Expr {
        syn::parse_quote!(__rticx_xbin_backend().global_core_id())
    }

    fn ipc_base_override(&self, _view_core: u32, source: u32, target: u32) -> Option<syn::Expr> {
        // The host mock pools are heap-backed, not at the synced addresses.
        Some(syn::parse_quote!(
            __rticx_xbin_backend().pool_base(#source, #target)
        ))
    }

    fn ring_doorbell_fn(&self, source: u32, target: u32, mut template: syn::ItemFn) -> syn::ItemFn {
        template.block = syn::parse_quote!({
            __rticx_xbin_backend().doorbell_send(#source, #target, task_id)
        });
        template
    }

    fn doorbell_interrupt(&self, target: u32, source: u32) -> syn::Ident {
        format_ident!("__rticx_xbin_router_{source}_{target}")
    }

    fn read_doorbell_msg_fn(
        &self,
        target: u32,
        source: u32,
        mut template: syn::ItemFn,
    ) -> syn::ItemFn {
        template.block = syn::parse_quote!({
            __rticx_xbin_backend().take_message(#source, #target)
        });
        template
    }

    fn custom_interrupt_path(&self, _core: u32) -> Option<syn::Path> {
        Some(syn::parse_quote!(__XbinInterrupt))
    }
}

/// Software-task backend of the compile fixture (M6.5-T5).
///
/// Binding [`SoftwarePass`] generates the `RticSwTask` trait the receiver
/// implements and the `__rticx_local_irq_pend` the router calls; the mock has
/// no interrupt controller, so the pend body runs the bound dispatcher ISR
/// directly.
struct CompileSwBackend;

impl SwPassBackend for CompileSwBackend {
    fn queue_path(&self) -> syn::Path {
        syn::parse_quote!(rticx_xbin_rt::Queue)
    }

    fn generate_local_pend_fn(&self, _core: u32, mut empty_body_fn: syn::ItemFn) -> syn::ItemFn {
        empty_body_fn.block = Box::new(syn::parse_quote!({
            match irq_nbr {
                __XbinInterrupt::IRQ0 => IRQ0(),
            }
        }));
        empty_body_fn
    }

    fn generate_cross_pend_fn(
        &self,
        _core: u32,
        _empty_body_fn: syn::ItemFn,
    ) -> Option<syn::ItemFn> {
        None
    }

    fn custom_interrupt_path(&self, _core: u32) -> Option<syn::Path> {
        Some(syn::parse_quote!(__XbinInterrupt))
    }
}

/// The core backend of the receiver fixture: [`MockCoreBackend`] with a
/// working resource-proxy lock body.
///
/// The mock replaces the whole lock body, which drops the `resource_ptr`
/// binding the generated body starts with. The receiver declares a shared
/// resource (`shared = [counter]`), so the fixture needs the same contract as
/// a real distribution: keep the generated body and call `f` with the
/// resource pointer. Everything else is delegated to the mock backend.
#[derive(Default)]
struct FixtureCoreBackend(MockCoreBackend);

impl CorePassBackend for FixtureCoreBackend {
    fn post_init(
        &self,
        app_args: &AppArgs,
        app_info: &SubApp,
        app_analysis: &SubAnalysis,
    ) -> Option<proc_macro2::TokenStream> {
        self.0.post_init(app_args, app_info, app_analysis)
    }

    fn generate_resource_proxy_lock_impl(
        &self,
        _app_args: &AppArgs,
        _app_info: &SubApp,
        mut incomplete_lock_fn: syn::ImplItemFn,
    ) -> syn::ImplItemFn {
        let lock_call: syn::Block = syn::parse_quote!({ f(unsafe { &mut *resource_ptr }) });
        incomplete_lock_fn.block.stmts.extend(lock_call.stmts);
        incomplete_lock_fn
    }

    fn generate_global_definitions(
        &self,
        app_args: &AppArgs,
        app_info: &SubApp,
        app_analysis: &SubAnalysis,
    ) -> Option<proc_macro2::TokenStream> {
        self.0
            .generate_global_definitions(app_args, app_info, app_analysis)
    }

    fn wrap_task_execution(
        &self,
        task: &RticTask,
        dispatch_task_call: proc_macro2::TokenStream,
    ) -> Option<proc_macro2::TokenStream> {
        self.0.wrap_task_execution(task, dispatch_task_call)
    }

    fn entry_name(&self, core: u32) -> syn::Ident {
        self.0.entry_name(core)
    }

    fn populate_idle_loop(&self) -> Option<proc_macro2::TokenStream> {
        self.0.populate_idle_loop()
    }

    fn generate_enable_global_interrupts(&self) -> Option<proc_macro2::TokenStream> {
        self.0.generate_enable_global_interrupts()
    }

    fn generate_interrupt_free_fn(&self, empty_body_fn: syn::ItemFn) -> syn::ItemFn {
        self.0.generate_interrupt_free_fn(empty_body_fn)
    }

    fn pre_codegen_validation(&self, app: &App, analysis: &Analysis) -> syn::Result<()> {
        self.0.pre_codegen_validation(app, analysis)
    }

    fn entry_attrs(&self) -> Vec<syn::Attribute> {
        self.0.entry_attrs()
    }

    fn task_attrs(&self, interrupt_name: syn::Ident) -> Vec<syn::Attribute> {
        self.0.task_attrs(interrupt_name)
    }
}

/// The receiver application: one task with a shared resource, its input, and
/// the mock backend used by the generated FIFO view. `__rticx_xbin_backend`
/// lives inside the app module because the generated code calls it there.
///
/// The `shared = [counter]` declaration is passed through to the core
/// `#[task(..)]` shape the pass injects, so the core pass computes the SRP
/// ceiling of `counter` for the receiver (M5.5).
fn receiver_app() -> syn::ItemMod {
    syn::parse_quote! {
        mod app {
            fn __rticx_xbin_backend() -> rticx_xbin_mock::MockBackend {
                static SYSTEM: std::sync::LazyLock<rticx_xbin_mock::MockSystem> =
                    std::sync::LazyLock::new(|| {
                        let mut system = rticx_xbin_mock::MockSystem::new();
                        system
                            .add_pool(0, 1, 4096)
                            .expect("mock IPC pool fits");
                        system
                    });
                SYSTEM.backend(1)
            }

            /// Fixture interrupt enum: `custom_interrupt_path` points the
            /// generated router and the software pass's pend function at it.
            #[allow(non_camel_case_types)]
            pub enum __XbinInterrupt {
                IRQ0,
            }

            #[shared]
            struct Shared {
                pub counter: u32,
            }

            #[sw_task(priority = 3, capacity = 2, spawn_by = 0, shared = [counter])]
            struct EncryptTask;

            impl RticSwTask for EncryptTask {
                type SpawnInput = ipc_types::EncryptReq;
                fn exec(&mut self, _input: Self::SpawnInput) {}
            }

            #[init]
            fn init() -> (Shared, TaskInits) {
                (Shared { counter: 0 }, TaskInits {})
            }
        }
    }
}

fn receiver_args() -> TokenStream {
    quote!(
        device = pac,
        cores = 1,
        core_ids = [1],
        external_cores = [0],
        ipc_dispatchers = [IRQ0]
    )
}

/// The fixture view with the receiver application's source hash recorded, as
/// `cargo xbin sync` would (M3-T4).
fn receiver_system() -> String {
    let mut view = SystemView::from_json(SYSTEM_JSON).expect("fixture system view");
    let application = view
        .apps
        .iter_mut()
        .find(|application| application.package == "app-m4")
        .expect("fixture app-m4");
    application.source_hash = rticx_xbin_pass::app_source_hash(&receiver_args(), &receiver_app());
    view.seal();
    view.to_json()
}

/// Runs the extension pass, the software pass and the core pass and returns
/// the expansion.
fn expand(system: &Path) -> String {
    let pass = XbinPass::with_system(system, "app-m4", "m4").with_backend(CompileBackend);
    let mut builder = RticMacroBuilder::new(FixtureCoreBackend::default());
    builder.bind_pre_core_pass(pass);
    builder.bind_pre_core_pass(SoftwarePass::new(CompileSwBackend));
    builder
        .build_rtic_macro2(receiver_args(), receiver_app(), None)
        .to_string()
}

/// Like [`expand`], but without the software pass: what a distribution whose
/// `swtasks` feature is off produces (M5.5).
fn expand_without_sw_pass(system: &Path) -> String {
    let pass = XbinPass::with_system(system, "app-m4", "m4").with_backend(CompileBackend);
    let mut builder = RticMacroBuilder::new(FixtureCoreBackend::default());
    builder.bind_pre_core_pass(pass);
    builder
        .build_rtic_macro2(receiver_args(), receiver_app(), None)
        .to_string()
}

fn cargo() -> PathBuf {
    std::env::var_os("CARGO")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("cargo"))
}

/// Writes the throwaway project that compiles the expansion.
fn write_project(root: &Path, expanded: &str) {
    let rt = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../rticx-xbin-rt")
        .canonicalize()
        .expect("the runtime crate ships with the workspace");
    let mock = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../mock/rticx-xbin-mock")
        .canonicalize()
        .expect("the mock crate ships with the workspace");

    std::fs::create_dir_all(root.join("src")).expect("src dir");
    std::fs::write(
        root.join("Cargo.toml"),
        format!(
            "[package]\nname = \"xbin-receiver-compile\"\nversion = \"0.0.0\"\nedition = \"2024\"\n\
             publish = false\n\n\
             [dependencies]\n\
             pac = {{ path = \"pac\" }}\n\
             rticx-xbin-rt = {{ path = \"{}\" }}\n\
             rticx-xbin-mock = {{ path = \"{}\" }}\n\n\
             [workspace]\n",
            rt.display(),
            mock.display()
        ),
    )
    .expect("project manifest");
    std::fs::write(
        root.join("src/lib.rs"),
        format!(
            "// @generated by the M3-T2 receiver compile test\n\
             #![allow(static_mut_refs, unused_imports, unused_variables, dead_code, \
             non_camel_case_types, non_snake_case)]\n\n{expanded}\n"
        ),
    )
    .expect("expansion");

    std::fs::create_dir_all(root.join("pac/src")).expect("pac dir");
    std::fs::write(
        root.join("pac/Cargo.toml"),
        "[package]\nname = \"pac\"\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n",
    )
    .expect("pac manifest");
    std::fs::write(root.join("pac/src/lib.rs"), "").expect("pac source");
}

#[test]
fn receiver_fixture_expands_and_compiles() {
    let dir = tempfile::tempdir().expect("tempdir");
    let system = dir.path().join("system.json");
    std::fs::write(&system, receiver_system()).expect("system.json");
    std::fs::write(dir.path().join("ipc_types.rs"), IPC_TYPES_RS).expect("ipc_types.rs");

    let expanded = expand(&system);

    // The pipeline ran to completion and emitted the M3-T2/M6.5-T3 items.
    assert!(
        !expanded.contains("compile_error"),
        "pipeline failed: {expanded}"
    );
    assert!(
        expanded.contains("fn IRQ0"),
        "the dispatcher handler bound to the pool entry is missing: {expanded}"
    );
    assert!(
        expanded.contains("__RticxXbinDispatcher0To1P3"),
        "the dispatcher is missing: {expanded}"
    );
    assert!(
        expanded.contains("__RticxXbinRouter0To1"),
        "the router is missing: {expanded}"
    );
    assert!(
        expanded.contains("__rticx_local_irq_pend") && expanded.contains("__XbinInterrupt :: IRQ0"),
        "the router does not pend the line dispatcher: {expanded}"
    );
    assert!(
        expanded.contains("implements_rtic_sw_task")
            && expanded.contains("impl RticSwTask for EncryptTask"),
        "the receiver was not turned into a core task: {expanded}"
    );
    assert!(
        expanded.contains("__rticx_xbin_assert_cross_core_message")
            && expanded.contains("CrossCoreMessage"),
        "the `SpawnInput: CrossCoreMessage` assertion is missing: {expanded}"
    );

    // The injected marker trait and the re-emitted `ipc_types` module survive
    // the software and core passes, so the compiler and `cargo rticx-expand`
    // see them (M1-T7).
    assert!(
        expanded.contains("pub mod ipc_types")
            && expanded.contains("pub struct EncryptReq")
            && expanded.contains("use super :: CrossCoreMessage"),
        "the injected `ipc_types` module was dropped by the pipeline: {expanded}"
    );

    // `shared = [counter]` is passed through to the core `#[task(..)]` shape,
    // so the core pass computes the SRP ceiling and generates the receiver's
    // shared-resource accessor (M5.5).
    assert!(
        expanded.contains("__encrypt_task_shared_resources"),
        "the receiver's shared resource was dropped: {expanded}"
    );

    // The shared-memory configuration is inlined at `BeforeInit` (D1); the
    // host backend leaves it unset, so the entry has no configure call and no
    // wrapper function is generated. The receiver produces no FIFO, so it has
    // no FIFO initializer, and no generated code arms doorbells (M6.5-T4).
    assert!(
        !expanded.contains("__rticx_xbin_init_shared"),
        "the removed shared-state initializer must not be generated: {expanded}"
    );
    assert!(
        !expanded.contains("__rticx_xbin_init_fifos_core0"),
        "a pure receiver initializes no FIFO: {expanded}"
    );
    assert!(
        !expanded.contains("__rticx_xbin_configure_shared_memory"),
        "the configure wrapper function must be gone (D1): {expanded}"
    );

    let project = dir.path().join("project");
    write_project(&project, &expanded);

    let status = Command::new(cargo())
        .arg("build")
        .arg("--quiet")
        .arg("--offline")
        .arg("--manifest-path")
        .arg(project.join("Cargo.toml"))
        .env("CARGO_TARGET_DIR", project.join("target"))
        .status()
        .expect("failed to run cargo");
    assert!(
        status.success(),
        "the expanded receiver fixture failed to compile"
    );
    assert!(
        project
            .join("target/debug/libxbin_receiver_compile.rlib")
            .is_file(),
        "the throwaway crate produced no library"
    );

    // M3-T4: the expansion `include_str!`s the system view, so editing it must
    // make rustc rebuild the crate through its dep-info. Sleep past the
    // mtime resolution some filesystems use before touching the view.
    std::thread::sleep(std::time::Duration::from_millis(1100));
    let mut edited = std::fs::read_to_string(&system).expect("system.json");
    edited.push('\n');
    std::fs::write(&system, edited).expect("edit system.json");
    let rebuild = Command::new(cargo())
        .arg("build")
        .arg("--offline")
        .arg("--manifest-path")
        .arg(project.join("Cargo.toml"))
        .env("CARGO_TARGET_DIR", project.join("target"))
        .output()
        .expect("failed to run cargo");
    assert!(
        rebuild.status.success(),
        "the rebuild after editing system.json failed:\n{}",
        String::from_utf8_lossy(&rebuild.stderr)
    );
    assert!(
        String::from_utf8_lossy(&rebuild.stderr).contains("Compiling xbin-receiver-compile"),
        "editing system.json must trigger a rebuild (include_str! dep-info):\n{}",
        String::from_utf8_lossy(&rebuild.stderr)
    );
}

#[test]
fn missing_sw_task_trait_is_a_compile_error() {
    // The `swtasks` feature is what binds `rticx-sw-pass`, which generates
    // the `RticSwTask` trait and its check function. A distribution that
    // binds only the cross-binary pass leaves `RticSwTask` undefined, so the
    // receiver's `impl RticSwTask` and the injected
    // `task_trait = RticSwTask` must fail to resolve (M5.5).
    let dir = tempfile::tempdir().expect("tempdir");
    let system = dir.path().join("system.json");
    std::fs::write(&system, receiver_system()).expect("system.json");
    std::fs::write(dir.path().join("ipc_types.rs"), IPC_TYPES_RS).expect("ipc_types.rs");

    let expanded = expand_without_sw_pass(&system);
    assert!(
        !expanded.contains("compile_error"),
        "pipeline failed: {expanded}"
    );

    let project = dir.path().join("project");
    write_project(&project, &expanded);

    let output = Command::new(cargo())
        .arg("build")
        .arg("--quiet")
        .arg("--offline")
        .arg("--manifest-path")
        .arg(project.join("Cargo.toml"))
        .env("CARGO_TARGET_DIR", project.join("target"))
        .output()
        .expect("failed to run cargo");
    assert!(
        !output.status.success(),
        "the receiver compiled although `RticSwTask` is undefined"
    );
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        stderr.contains("RticSwTask"),
        "the error does not name the missing `RticSwTask` trait:\n{stderr}"
    );
}
