//! End-to-end metadata collection and merge over the checked-in fixture
//! (M1-T4, M1-T5).
//!
//! `sync` must drive `cargo clean -p <package>` followed by
//! `cargo check -p <package> --bin <target>` with `RTICX_XBIN_META_OUT` over
//! `fixtures/metadata`, read back one manifest per application, and merge the
//! manifests into the validated project view.

use std::path::{Path, PathBuf};

use rticx_xbin_driver::{SYSTEM_FILE, sync};
use rticx_xbin_proto::{
    DoorbellEntry, FifoEntry, Hash64, RTICX_GENERATION, SystemView, layout_hash,
};
use tempfile::tempdir;

/// Root of the checked-in metadata fixture.
fn fixture_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../fixtures/metadata")
        .canonicalize()
        .expect("the metadata fixture ships with the driver crate")
}

#[test]
fn sync_collects_a_manifest_for_every_fixture_application() {
    let root = fixture_root();
    let output_dir = root.join("target/rticx-xbin");

    // A manifest left over from an earlier run must never be read back.
    std::fs::create_dir_all(&output_dir).expect("output dir");
    std::fs::write(output_dir.join("m4.xbin.json"), "{ \"stale\": true }").expect("stale write");

    let outcome = sync(&root).expect("sync collects the fixture manifests");

    assert_eq!(outcome.output_dir, output_dir);
    assert_eq!(outcome.applications().len(), 2);
    assert_eq!(outcome.manifests.len(), 2, "one manifest per application");
    assert_eq!(
        outcome
            .manifests
            .iter()
            .map(|manifest| manifest.target.name.as_str())
            .collect::<Vec<_>>(),
        ["m7", "m4"],
        "manifests follow `rticx.toml` order"
    );

    let producer = outcome.manifest("m7").expect("m7 manifest");
    assert_eq!(producer.package, "app-m7");
    assert_eq!(producer.core_ids.as_deref(), Some(&[0][..]));
    assert_eq!(producer.external_cores, [1]);
    assert!(
        producer.receivers.is_empty(),
        "the producer declares nothing (M5.5)"
    );

    let receiver = outcome.manifest("m4").expect("m4 manifest");
    assert_eq!(receiver.package, "app-m4");
    assert_eq!(receiver.core_ids.as_deref(), Some(&[1][..]));
    assert_eq!(receiver.external_cores, [0]);
    assert_eq!(receiver.receivers.len(), 1);
    let task = &receiver.receivers[0];
    assert_eq!(task.name, "EncryptTask");
    assert_eq!(task.core, 0, "receiver `core` is a local index");
    assert_eq!(task.spawn_by, 0, "the global producer core id");
    assert_eq!(task.priority, 3);
    assert_eq!(task.capacity, 2);
    assert_eq!(task.input_type_name(), "EncryptReq");

    for target in ["m7", "m4"] {
        assert!(
            output_dir.join(format!("{target}.xbin.json")).is_file(),
            "the {target} manifest is on disk"
        );
    }

    let idl = outcome
        .idl
        .as_ref()
        .expect("the fixture declares ipc-types.toml");
    assert!(idl.has_type("EncryptReq"));
    assert_eq!(idl.messages().len(), 1);

    // -- M1-T7: the generated `ipc-types` crate lives in the project ---------
    let ipc_types = outcome
        .ipc_types
        .as_ref()
        .expect("the fixture IDL generates the crate");
    assert_eq!(ipc_types.path, root.join("ipc-types"));
    assert!(
        ipc_types.status.is_noop(),
        "the checked-in generated crate must be up to date: {:?}",
        ipc_types.status
    );
    let lib_rs = std::fs::read_to_string(ipc_types.path.join("src/lib.rs")).expect("lib.rs");
    assert!(
        lib_rs.starts_with("// @generated by `cargo xbin sync`"),
        "{lib_rs}"
    );
    assert!(lib_rs.contains("pub struct EncryptReq {"), "{lib_rs}");
    assert!(
        lib_rs.contains("pub const SIZE_ENCRYPT_REQ: usize = 12;"),
        "{lib_rs}"
    );
    assert!(
        lib_rs.contains("pub const LAYOUT_HASH: u64 = 0x"),
        "{lib_rs}"
    );
    let cargo_toml =
        std::fs::read_to_string(ipc_types.path.join("Cargo.toml")).expect("Cargo.toml");
    assert!(
        cargo_toml.contains("rticx-xbin-rt = { path = \"../../../crates/rticx-xbin-rt\" }"),
        "{cargo_toml}"
    );

    let merged = outcome
        .merged
        .as_ref()
        .expect("the fixture manifests merge and validate");
    assert_eq!(merged.tasks().len(), 1);
    let task = &merged.tasks()[0];
    assert_eq!(task.id(), 1);
    assert_eq!(task.name(), "EncryptTask");
    assert_eq!(task.receiver_core(), 1, "global receiver core id");
    assert_eq!(task.spawner_core(), 0, "global spawner core id");
    assert_eq!(task.priority(), 3);
    assert_eq!(task.capacity(), 2);
    assert_eq!(task.input_type(), "EncryptReq");
    assert_eq!(task.elem_size(), 12);
    assert_eq!(task.fifo_offset(), 0);
    assert_eq!(task.fifo_depth(), 3);
    assert_eq!(task.fifo_bytes(), 100);
    assert_eq!(merged.regions().len(), 2);

    // -- M1-T6: the allocated system view is emitted ------------------------
    let system = outcome.system.as_ref().expect("sync emits the system view");
    let bytes = std::fs::read_to_string(output_dir.join(SYSTEM_FILE))
        .expect("system.json is written to the output directory");
    assert_eq!(bytes, system.to_json(), "the emitted bytes match the view");
    assert!(system.verify_topology_hash());
    assert_eq!(SystemView::from_json(&bytes).expect("parse"), *system);
    assert_eq!(system.schema_version, 1);
    assert_eq!(system.rticx_generation, RTICX_GENERATION);
    assert_eq!(
        system.layout_hash,
        Hash64::new(layout_hash(idl).expect("layout hash"))
    );

    assert_eq!(
        system
            .tasks
            .iter()
            .map(|task| (
                task.name.as_str(),
                task.receiver_core,
                task.spawner_core,
                task.priority,
                task.capacity,
                task.input_type.as_str(),
            ))
            .collect::<Vec<_>>(),
        [("EncryptTask", 1, 0, 3, 2, "EncryptReq")]
    );
    assert_eq!(
        system.tasks[0].fifo,
        FifoEntry {
            source: 0,
            target: 1,
            offset: 0,
            elem_size: 12,
            depth: 3,
        }
    );
    assert_eq!(
        system.doorbells,
        [DoorbellEntry {
            source: 0,
            target: 1,
            priority: 3,
            line: 0,
        }]
    );

    // M1-T6 acceptance: a second full sync produces byte-identical output.
    let second = sync(&root).expect("a second sync succeeds");
    assert_eq!(
        std::fs::read_to_string(output_dir.join(SYSTEM_FILE)).expect("system.json"),
        bytes,
        "identical inputs must produce byte-identical system.json"
    );
    assert_eq!(second.system.as_ref(), outcome.system.as_ref());
    assert!(
        second
            .ipc_types
            .as_ref()
            .expect("the fixture IDL generates the crate")
            .status
            .is_noop(),
        "an unchanged IDL keeps the generated crate untouched"
    );
}

#[test]
fn sync_reports_a_failing_cargo_check() {
    let dir = tempdir().expect("tempdir");
    std::fs::write(
        dir.path().join("Cargo.toml"),
        "[workspace]\nresolver = \"2\"\nmembers = [\"broken\"]\n",
    )
    .expect("workspace manifest");
    std::fs::create_dir_all(dir.path().join("broken/src")).expect("mkdirs");
    std::fs::write(
        dir.path().join("broken/Cargo.toml"),
        "[package]\nname = \"broken\"\nversion = \"0.1.0\"\nedition = \"2024\"\n",
    )
    .expect("package manifest");
    std::fs::write(
        dir.path().join("broken/src/main.rs"),
        "fn main() { compile_error!(\"fixture check failure\"); }\n",
    )
    .expect("source");
    std::fs::write(
        dir.path().join("rticx.toml"),
        "schema = 1\n\n[[application]]\npackage = \"broken\"\n\
         target = { kind = \"bin\", name = \"broken\" }\ncore_ids = [0]\n",
    )
    .expect("project manifest");

    let error = sync(dir.path())
        .expect_err("the broken application fails to check")
        .to_string();

    assert!(
        error.contains("`cargo check --package broken --bin broken` failed"),
        "{error}"
    );
    assert!(error.contains("fixture check failure"), "{error}");
}

#[test]
fn sync_reports_a_merge_failure() {
    let dir = tempdir().expect("tempdir");
    write_merge_project(dir.path());

    let error = sync(dir.path())
        .expect_err("the region is too small for the task FIFO")
        .to_string();

    assert_eq!(
        error,
        "task `EncryptTask` does not fit the `0->1` region: 100 bytes needed, 99 available"
    );
}

const PRODUCER_MAIN: &str = r#"
use metadata_macro::app;

#[app(device = fixture, cores = 1, core_ids = [0], external_cores = [1])]
mod app {}

fn main() {}
"#;

const RECEIVER_MAIN: &str = r#"
use metadata_macro::app;

#[app(
    device = fixture,
    cores = 1,
    core_ids = [1],
    external_cores = [0],
    ipc_dispatchers = [IRQ0]
)]
mod app {
    trait RticSwTask {
        type SpawnInput;
        fn exec(&mut self, input: Self::SpawnInput);
    }

    struct EncryptReq;

    #[sw_task(priority = 3, capacity = 2, spawn_by = 0)]
    struct EncryptTask;

    impl RticSwTask for EncryptTask {
        type SpawnInput = EncryptReq;
        fn exec(&mut self, _input: Self::SpawnInput) {}
    }
}

fn main() {}
"#;

/// Writes a two-application project whose `0->1` region is 99 bytes instead
/// of the required 100, reusing the checked-in metadata macro stand-in.
fn write_merge_project(root: &Path) {
    let macro_path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../fixtures/metadata/metadata-macro")
        .canonicalize()
        .expect("the metadata fixture ships with the driver crate");

    std::fs::write(
        root.join("Cargo.toml"),
        "[workspace]\nresolver = \"2\"\nmembers = [\"app-m7\", \"app-m4\"]\n",
    )
    .expect("workspace manifest");

    for (package, bin, source) in [
        ("app-m7", "m7", PRODUCER_MAIN),
        ("app-m4", "m4", RECEIVER_MAIN),
    ] {
        let dir = root.join(package);
        std::fs::create_dir_all(dir.join("src")).expect("mkdirs");
        std::fs::write(
            dir.join("Cargo.toml"),
            format!(
                "[package]\nname = \"{package}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\
                 publish = false\n\n\
                 [[bin]]\nname = \"{bin}\"\npath = \"src/main.rs\"\n\n\
                 [dependencies]\nmetadata-macro = {{ path = \"{}\" }}\n",
                macro_path.display()
            ),
        )
        .expect("package manifest");
        std::fs::write(dir.join("src/main.rs"), source).expect("source");
    }

    std::fs::write(
        root.join("rticx.toml"),
        "schema = 1\n\n\
         [[application]]\npackage = \"app-m7\"\ntarget = { kind = \"bin\", name = \"m7\" }\n\
         core_ids = [0]\n\n\
         [[application]]\npackage = \"app-m4\"\ntarget = { kind = \"bin\", name = \"m4\" }\n\
         core_ids = [1]\n\n\
         [ipc.regions]\n\
         \"0->1\" = { base_from_source = 0x30040000, base_from_target = 0x30040000, size = 99 }\n",
    )
    .expect("project manifest");

    std::fs::write(
        root.join("ipc-types.toml"),
        "schema = 1\n\n[message.EncryptReq]\nfields = { addr = \"u32\", len = \"u32\", key = \"u32\" }\n",
    )
    .expect("idl");
}
